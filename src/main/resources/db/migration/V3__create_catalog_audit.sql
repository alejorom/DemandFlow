CREATE TABLE demandflow.catalog_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mutation_id UUID NOT NULL,
    entity_type VARCHAR(16) NOT NULL,
    period_id BIGINT,
    rate_id BIGINT,
    operation VARCHAR(12) NOT NULL,
    field VARCHAR(32) NOT NULL,
    before_value TEXT,
    after_value TEXT NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor_origin VARCHAR(10) NOT NULL,
    CONSTRAINT fk_catalog_audit_period FOREIGN KEY (period_id)
        REFERENCES demandflow.tariff_period (id),
    CONSTRAINT fk_catalog_audit_rate FOREIGN KEY (rate_id)
        REFERENCES demandflow.hourly_rate (id),
    CONSTRAINT ck_catalog_audit_entity CHECK (
        (entity_type = 'TARIFF_PERIOD' AND period_id IS NOT NULL AND rate_id IS NULL) OR
        (entity_type = 'HOURLY_RATE' AND rate_id IS NOT NULL AND period_id IS NULL)),
    CONSTRAINT ck_catalog_audit_operation CHECK (
        operation IN ('CREATE', 'UPDATE', 'DEACTIVATE', 'REACTIVATE')),
    CONSTRAINT ck_catalog_audit_field CHECK (
        (entity_type = 'TARIFF_PERIOD' AND field IN ('label', 'start_date', 'end_date', 'active')) OR
        (entity_type = 'HOURLY_RATE' AND field IN ('period_id', 'type_id', 'amount_cop', 'active'))),
    CONSTRAINT ck_catalog_audit_change CHECK (before_value IS DISTINCT FROM after_value),
    CONSTRAINT ck_catalog_audit_before CHECK (operation = 'CREATE' OR before_value IS NOT NULL),
    CONSTRAINT ck_catalog_audit_origin CHECK (actor_origin IN ('LOCAL_USER', 'SYSTEM')),
    CONSTRAINT uq_catalog_audit_mutation_field UNIQUE (mutation_id, field)
);

CREATE INDEX ix_catalog_audit_period ON demandflow.catalog_audit_event (period_id);
CREATE INDEX ix_catalog_audit_rate ON demandflow.catalog_audit_event (rate_id);

GRANT SELECT ON demandflow.tariff_period, demandflow.requirement_type,
    demandflow.hourly_rate, demandflow.catalog_audit_event TO demandflow_app;
GRANT INSERT (label, start_date, end_date, active, version)
    ON demandflow.tariff_period TO demandflow_app;
GRANT UPDATE (label, start_date, end_date, active, version)
    ON demandflow.tariff_period TO demandflow_app;
GRANT INSERT (period_id, type_id, amount_cop, active, version)
    ON demandflow.hourly_rate TO demandflow_app;
GRANT UPDATE (amount_cop, active, version)
    ON demandflow.hourly_rate TO demandflow_app;
GRANT INSERT (mutation_id, entity_type, period_id, rate_id, operation, field,
    before_value, after_value, occurred_at, actor_origin)
    ON demandflow.catalog_audit_event TO demandflow_app;
GRANT USAGE ON SEQUENCE demandflow.tariff_period_id_seq, demandflow.hourly_rate_id_seq,
    demandflow.catalog_audit_event_id_seq TO demandflow_app;
