CREATE TABLE demandflow.tariff_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_tariff_period_label CHECK (length(btrim(label)) > 0),
    CONSTRAINT ck_tariff_period_dates CHECK (
        isfinite(start_date) AND isfinite(end_date) AND start_date <= end_date),
    CONSTRAINT ck_tariff_period_version CHECK (version >= 0),
    CONSTRAINT ex_tariff_period_dates EXCLUDE USING gist (
        daterange(start_date, end_date, '[]') WITH &&)
);

CREATE TABLE demandflow.requirement_type (
    id SMALLINT PRIMARY KEY,
    code VARCHAR(7) NOT NULL UNIQUE,
    name VARCHAR(7) NOT NULL,
    CONSTRAINT ck_requirement_type_fixed CHECK (
        (id = 1 AND code = 'Soporte' AND name = 'Soporte') OR
        (id = 2 AND code = 'Feature' AND name = 'Feature'))
);

INSERT INTO demandflow.requirement_type (id, code, name)
VALUES (1, 'Soporte', 'Soporte'), (2, 'Feature', 'Feature');

CREATE TABLE demandflow.hourly_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id BIGINT NOT NULL,
    type_id SMALLINT NOT NULL,
    amount_cop NUMERIC(15,2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_hourly_rate_period FOREIGN KEY (period_id)
        REFERENCES demandflow.tariff_period (id),
    CONSTRAINT fk_hourly_rate_type FOREIGN KEY (type_id)
        REFERENCES demandflow.requirement_type (id),
    CONSTRAINT uq_hourly_rate_period_type UNIQUE (period_id, type_id),
    CONSTRAINT ck_hourly_rate_amount CHECK (amount_cop > 0 AND amount_cop <= 9999999999999.99),
    CONSTRAINT ck_hourly_rate_version CHECK (version >= 0)
);

CREATE INDEX ix_hourly_rate_type ON demandflow.hourly_rate (type_id);
